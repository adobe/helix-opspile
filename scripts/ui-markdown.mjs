/**
 * Writes src/ui-markdown.bundle.js: src/ui-markdown.js and micromark, bundled for the
 * browser, as a string that src/page.js puts into the inbox page.
 *
 *   node scripts/ui-markdown.mjs
 *
 * The file is not committed: cloudflare.config.ts runs this on every cf deploy and cf dev,
 * and npm runs it before lint, test and ui:dev (`npm run build` by hand).
 */

import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'src', 'ui-markdown.bundle.js');

/** The bundle, as the module that src/page.js imports. */
export async function bundle() {
  const result = await build({
    entryPoints: [join(root, 'src', 'ui-markdown.js')],
    bundle: true,
    format: 'iife',
    globalName: 'Markdown',
    minify: true,
    target: 'es2022',
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
  });
  // In an inline <script>, `</script` would end it.
  const code = result.outputFiles[0].text.trim().replace(/<\/(script)/gi, '<\\/$1');
  return `/*
 * Generated by scripts/ui-markdown.mjs from src/ui-markdown.js; do not edit.
 *
 * Includes micromark and its GFM extensions, (c) Titus Wormer, MIT License:
 * https://github.com/micromark/micromark
 */
/* eslint-disable */
export default ${JSON.stringify(code)};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = await bundle();
  await writeFile(OUT, source);
  console.log(`wrote ${OUT} (${Math.round(source.length / 1024)} KB)`);
}
