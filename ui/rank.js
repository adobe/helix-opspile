  /**
   * A model's value of a thread's features: boosted trees (`trees`, each `[feature, threshold,
   * left, right]` or a leaf, over `names`), summed; or a linear model (`weights`).
   */
  function value(f, model) {
    let s = 0;
    if (model.trees) {
      const x = model.names.map((n) => f[n] || 0);
      for (const tree of model.trees) {
        let n = tree;
        while (Array.isArray(n)) n = x[n[0]] <= n[1] ? n[2] : n[3];
        s += n;
      }
      return s;
    }
    for (const [k, w] of Object.entries(model.weights)) s += w * (f[k] || 0);
    return s;
  }

  /** The score of an inbox entry, or null without a model. */
  function score(t, now = Date.now(), model = MODEL) {
    return model ? value(features(t, now), model) : null;
  }

  /**
   * What each feature adds to a thread's score, largest first (for the console): the score
   * less the score with that feature at 0 (for a linear model, its weight times its value).
   */
  function explain(t, now = Date.now(), model = MODEL) {
    if (!model) return [];
    const f = features(t, now);
    const all = value(f, model);
    return (model.trees ? model.names : Object.keys(model.weights))
      .map((k) => [k, all - value({ ...f, [k]: 0 }, model)])
      .filter(([, v]) => Math.abs(v) > 1e-9).sort((a, b) => Math.abs(b[1]) - Math.abs(a[1]));
  }

  return {
    features, names: NAMES, score, explain, model: MODEL,
  };
